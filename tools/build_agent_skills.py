#!/usr/bin/env python3
"""Generate thin Agent Skills so non-Claude agents can run the workflows.

.claude/ stays the single source of truth; each generated SKILL.md only points to it.
Usage: python3 tools/build_agent_skills.py [--check]
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# name -> (source spec, description)
WORKFLOWS = {
    "setup": ("commands/setup.md", "Build the candidate profile from documents, a pasted CV, or an interview."),
    "scrape": ("skills/job-scraper/SKILL.md", "Search job portals for postings that match the candidate profile."),
    "rank": ("commands/rank.md", "Score scraped postings into a ranked shortlist."),
    "apply": ("commands/apply.md", "Evaluate a job posting, then draft and review a tailored CV and cover letter."),
    "interview": ("commands/interview.md", "Prepare for an interview on a tracked application."),
    "outcome": ("commands/outcome.md", "Record application results and draft follow-ups."),
    "upskill": ("skills/upskill/SKILL.md", "Analyze skill gaps and build a learning plan."),
    "expand": ("commands/expand.md", "Add competencies from documents and public profiles to the candidate profile."),
    "html-report": ("commands/html-report.md", "Generate an offline dashboard of applications."),
    "gmail-sync": ("commands/gmail-sync.md", "Propose application status updates from Gmail."),
    "notion-sync": ("commands/notion-sync.md", "Publish a one-way view of the pipeline to Notion."),
    "add-portal": ("commands/add-portal.md", "Create a search skill for a new job board."),
    "add-template": ("commands/add-template.md", "Register a custom CV or cover letter template."),
    "reset": ("commands/reset.md", "Wipe profile data or documents. Run only when the user explicitly asks."),
    "assistant": ("skills/job-application-assistant/SKILL.md", "Help with job fit, CVs, cover letters, and application forms."),
}

TEMPLATE = """---
name: job-{name}
description: {description}
---

<!-- Generated by tools/build_agent_skills.py. Do not edit. -->

1. Read `docs/any-agent.md` (tool mapping and safety rules). Paths are relative to the repository root.
2. Read `CLAUDE.md` (the candidate profile and project rules).
3. Read `.claude/{source}` and follow it. Wherever it says `$ARGUMENTS`, use the text the user gave with this request.
"""


def main() -> int:
    check = "--check" in sys.argv[1:]
    stale = []
    for name, (source, description) in WORKFLOWS.items():
        if not (ROOT / ".claude" / source).is_file():
            print(f"missing source: .claude/{source}")
            return 1
        path = ROOT / ".agents" / "skills" / f"job-{name}" / "SKILL.md"
        text = TEMPLATE.format(name=name, source=source, description=description)
        if check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
    unmapped = {p.name for p in (ROOT / ".claude" / "commands").glob("*.md")} - {
        Path(s).name for s, _ in WORKFLOWS.values() if s.startswith("commands/")
    }
    if unmapped:
        stale += [f"unmapped command: {n}" for n in sorted(unmapped)]
    if stale:
        print("\n".join(stale))
        return 1
    print(f"agent skills: OK ({len(WORKFLOWS)})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
